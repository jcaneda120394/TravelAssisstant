#!/usr/bin/env node
/**
 * Writes EXPO_PUBLIC_* into .env for Expo web builds on Vercel/CI.
 * Expo inlines these at export time; without a file, some CI paths leave them empty
 * and the app falls back to "Demo auth mode".
 */
const fs = require('fs');
const path = require('path');

const KEYS = [
  'EXPO_PUBLIC_APP_ENV',
  'EXPO_PUBLIC_APP_NAME',
  'EXPO_PUBLIC_SUPABASE_URL',
  'EXPO_PUBLIC_SUPABASE_ANON_KEY',
  'EXPO_PUBLIC_USE_MOCK_PROVIDERS',
  'EXPO_PUBLIC_POSTHOG_KEY',
  'EXPO_PUBLIC_POSTHOG_HOST',
  'EXPO_PUBLIC_SENTRY_DSN',
];

const lines = ['# Generated by scripts/write-expo-env.js for CI/Vercel builds'];
const missing = [];

for (const key of KEYS) {
  const value = process.env[key];
  if (value == null || value === '') {
    if (key === 'EXPO_PUBLIC_SUPABASE_URL' || key === 'EXPO_PUBLIC_SUPABASE_ANON_KEY') {
      missing.push(key);
    }
    continue;
  }
  const escaped = String(value).replace(/\\/g, '\\\\').replace(/"/g, '\\"');
  lines.push(`${key}="${escaped}"`);
}

const out = path.join(process.cwd(), '.env');
fs.writeFileSync(out, `${lines.join('\n')}\n`, 'utf8');

console.log(`[write-expo-env] Wrote ${out} (${lines.length - 1} vars)`);
if (missing.length) {
  console.warn(
    `[write-expo-env] WARNING: missing ${missing.join(', ')} — build will show Demo auth mode`,
  );
  if (process.env.VERCEL === '1' || process.env.CI === 'true') {
    console.error(
      '[write-expo-env] Set EXPO_PUBLIC_SUPABASE_URL and EXPO_PUBLIC_SUPABASE_ANON_KEY in Vercel Project Settings → Environment Variables, then redeploy.',
    );
    process.exit(1);
  }
}
